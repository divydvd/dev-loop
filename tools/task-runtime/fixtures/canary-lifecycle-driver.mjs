import assert from "node:assert/strict";
import fs from "node:fs";
await import(process.argv[2]);
const { options, session, callbacks } = globalThis.taskTestHost;
const stop = options.hooks.onAgentStop;
assert.equal(stop({ stopReason: "end_turn" }), undefined, "discovery must precede correction");
const marker = options.tools.find(tool => tool.name === "task_canary_marker");
assert.equal(marker.handler(), "CANARY_MARKED");
assert.equal(stop({ stopReason: "end_turn" }).decision, "block");
assert.equal(stop({ stopReason: "end_turn", stopHookActive: true }), undefined);
assert.equal(stop({ stopReason: "end_turn" }), undefined);
let aborts = 0, sends = 0;
session.abort = async () => { aborts++; callbacks.get("abort")({}); };
session.send = async () => { sends++; return "unexpected-message"; };
callbacks.get("session.idle")({});
const cancel = options.tools.find(tool => tool.name === "task_canary_cancel");
assert.ok(cancel, "the canary must expose a native cancellation control");
assert.equal(cancel.handler(), "CANARY_ABORT_REQUESTED");
assert.equal(cancel.handler(), "CANARY_ABORT_ALREADY_REQUESTED");
await new Promise(resolve => setTimeout(resolve, 80));
assert.equal(aborts, 1);
assert.equal(sends, 0, "cancellation must prevent pending idle delivery");
assert.equal(stop({ stopReason: "end_turn" }), undefined);
const observations = fs.readFileSync(process.env.TASK_CANARY_OUTPUT, "utf8").trim().split("\n").map(JSON.parse);
assert.equal(observations.filter(event => event.kind === "block").length, 1);
assert.equal(observations.filter(event => event.kind === "cancelled").length, 1);
assert.equal(observations.filter(event => event.kind === "abort-acknowledged").length, 1);
console.log("bounded lifecycle and native cancellation preserved");
